#!/usr/bin/env python3
"""Generate a bounded Nox provider from the pinned IANA archive."""

import argparse
import datetime as dt
import hashlib
import io
import os
from pathlib import Path
import re
import subprocess
import sys
import tarfile
import tempfile
from zoneinfo import ZoneInfo


ARCHIVE_SHA256 = "01b4a91cec5167ed48c11e8ab78f2048cead78ce94b0cafcad0ae8c5a3044d3d"
MAX_ARCHIVE_BYTES = 4 * 1024 * 1024
TZDATA_VERSION = "2026f"
TOOL_VERSION = "2022g"
CASES = (
    ("Europe/Berlin", 2024, 2026),
    ("Australia/Lord_Howe", 2024, 2026),
    ("Asia/Kathmandu", 1985, 1988),
)
SOURCE_FILES = ("europe", "australasia", "asia")
ALL_SOURCE_FILES = (
    "africa", "antarctica", "asia", "australasia", "europe",
    "northamerica", "southamerica", "etcetera", "backward",
)
ENV = {**os.environ, "LC_ALL": "C"}


def run(*command: str, env: dict[str, str] = ENV) -> str:
    return subprocess.run(command, env=env, check=True, capture_output=True, text=True, timeout=30).stdout


def utc_start(year: int) -> int:
    return int(dt.datetime(year, 1, 1, tzinfo=dt.timezone.utc).timestamp())


def offset_at(zone: ZoneInfo, utc: int) -> int:
    offset = dt.datetime.fromtimestamp(utc, tz=zone).utcoffset()
    assert offset is not None
    return int(offset.total_seconds())


def read_verified_archive(archive: Path) -> bytes:
    with archive.open("rb") as stream:
        data = stream.read(MAX_ARCHIVE_BYTES + 1)
    if len(data) > MAX_ARCHIVE_BYTES:
        raise ValueError("tzdata archive exceeds size limit")
    if hashlib.sha256(data).hexdigest() != ARCHIVE_SHA256:
        raise ValueError("unexpected tzdata2026f archive checksum")
    return data


def generate(archive: Path, cases: tuple[tuple[str, int, int], ...], fixture_mode: bool) -> str:
    data = read_verified_archive(archive)
    for tool in ("zic", "zdump"):
        if run(tool, "--version").strip() != f"{tool} (tzcode) {TOOL_VERSION}":
            raise ValueError(f"fixture generation requires {tool} {TOOL_VERSION}")
    lookup = "fixture_rules" if fixture_mode else "_iana_rules"
    provider = "FixtureZoneProvider" if fixture_mode else "IanaZoneProvider"
    lines = [
        "# Generated by scripts/generate_timezone_fixture.py from IANA tzdata 2026f.",
        "from chronos.timezone import TimezoneError, ZoneRules, ZoneTransition",
        "",
        f"def {lookup}(zone_name: str) -> ZoneRules:",
    ]
    source_files = SOURCE_FILES if fixture_mode else ALL_SOURCE_FILES
    with tempfile.TemporaryDirectory(prefix="chronos-tz-fixture-") as directory:
        root = Path(directory)
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as source:
            for name in source_files:
                member = source.extractfile(name)
                if member is None:
                    raise ValueError(f"missing IANA source: {name}")
                (root / name).write_bytes(member.read())
        compiled = root / "compiled"
        run("zic", "-d", str(compiled), *(str(root / name) for name in source_files))
        for name, first, end in cases:
            path = compiled / name
            if not path.is_file():
                raise ValueError(f"unknown IANA zone: {name}")
            with path.open("rb") as stream:
                zone = ZoneInfo.from_file(stream, key=name)
            start_seconds, end_seconds = utc_start(first), utc_start(end)
            initial_offset = offset_at(zone, start_seconds)
            dump = run("zdump", "-V", "-c", f"{first},{end}", name, env={**ENV, "TZDIR": str(compiled)})
            pairs = []
            for line in dump.splitlines():
                instant, detail = line.removeprefix(name).strip().split(" UT = ", 1)
                utc = int(dt.datetime.strptime(instant, "%a %b %d %H:%M:%S %Y").replace(tzinfo=dt.timezone.utc).timestamp())
                offset = int(detail.rsplit("gmtoff=", 1)[1])
                if offset_at(zone, utc) != offset:
                    raise ValueError("zoneinfo and zdump offsets differ")
                pairs.append((utc, offset))
            if len(pairs) % 2:
                raise ValueError("unpaired zdump boundary")
            transitions = []
            previous_offset = initial_offset
            for (before, old), (after, new) in zip(pairs[::2], pairs[1::2]):
                if after != before + 1:
                    raise ValueError("unexpected zdump boundary")
                if after == start_seconds and new == initial_offset:
                    continue
                if old != previous_offset or not start_seconds < after < end_seconds:
                    raise ValueError("inconsistent zone offsets or coverage")
                previous_offset = new
                if old == new:
                    continue
                transitions.append(f"ZoneTransition({after * 1000}, {new})")
            if len(transitions) > 512 or previous_offset != offset_at(zone, end_seconds - 1):
                raise ValueError("zone transitions exceed limits or do not cover the window")
            lines.append(f'    if zone_name == "{name}":')
            lines.append(f"        return ZoneRules({start_seconds * 1000}, {end_seconds * 1000}, {initial_offset}, [{', '.join(transitions)}])")
    error = "unknown timezone fixture" if fixture_mode else "unknown timezone in this provider"
    lines.append(f'    raise TimezoneError("{error}")')
    lines.extend([
        "",
        f"class {provider}:",
        "    def version(self) -> str:",
        "",
        f'        return "{TZDATA_VERSION}"',
        "",
        "    def rules_for(self, zone_name: str) -> ZoneRules:",
        "",
        f"        return {lookup}(zone_name)",
    ])
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("--zone", action="append", help="IANA name, repeat for up to 64 zones")
    parser.add_argument("--from-year", type=int)
    parser.add_argument("--until-year", type=int, help="exclusive UTC end year")
    args = parser.parse_args()
    if args.zone is None:
        if args.from_year is not None or args.until_year is not None:
            parser.error("coverage years require at least one zone")
        requested = CASES
    else:
        first, end = args.from_year, args.until_year
        if first is None or end is None or not 1970 <= first < end <= 9999 or end - first > 100:
            parser.error("choose a UTC year range within 1970–9999 and at most 100 years long")
        if len(args.zone) > 64 or len(set(args.zone)) != len(args.zone):
            parser.error("choose at most 64 distinct zones")
        for name in args.zone:
            valid = re.fullmatch(r"[A-Za-z0-9_+.-]+(?:/[A-Za-z0-9_+.-]+)*", name)
            if len(name) > 128 or not valid or any(part in {".", ".."} for part in name.split("/")):
                parser.error("invalid IANA zone name")
        requested = tuple((name, first, end) for name in sorted(args.zone))
    try:
        print(generate(args.archive, requested, args.zone is None), end="")
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(f"timezone generation failed: {error}", file=sys.stderr)
        raise SystemExit(1)
