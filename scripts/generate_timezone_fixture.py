#!/usr/bin/env python3
"""Emit the bounded Nox prototype fixture from the pinned IANA archive."""

import datetime as dt
import hashlib
import os
from pathlib import Path
import subprocess
import sys
import tarfile
import tempfile
from zoneinfo import ZoneInfo


ARCHIVE_SHA256 = "01b4a91cec5167ed48c11e8ab78f2048cead78ce94b0cafcad0ae8c5a3044d3d"
TZDATA_VERSION = "2026f"
TOOL_VERSION = "2022g"
CASES = (
    ("Europe/Berlin", 2024, 2026),
    ("Australia/Lord_Howe", 2024, 2026),
    ("Asia/Kathmandu", 1985, 1988),
)
SOURCE_FILES = ("europe", "australasia", "asia")
ENV = {**os.environ, "LC_ALL": "C"}


def run(*command: str, env: dict[str, str] = ENV) -> str:
    return subprocess.run(command, env=env, check=True, capture_output=True, text=True, timeout=30).stdout


def utc_start(year: int) -> int:
    return int(dt.datetime(year, 1, 1, tzinfo=dt.timezone.utc).timestamp())


def offset_at(zone: ZoneInfo, utc: int) -> int:
    offset = dt.datetime.fromtimestamp(utc, tz=zone).utcoffset()
    assert offset is not None
    return int(offset.total_seconds())


def fixture(archive: Path) -> str:
    if hashlib.sha256(archive.read_bytes()).hexdigest() != ARCHIVE_SHA256:
        raise ValueError("unexpected tzdata2026f archive checksum")
    for tool in ("zic", "zdump"):
        if run(tool, "--version").strip() != f"{tool} (tzcode) {TOOL_VERSION}":
            raise ValueError(f"fixture generation requires {tool} {TOOL_VERSION}")
    lines = [
        "# Generated by scripts/generate_timezone_fixture.py from IANA tzdata 2026f.",
        "from proofs.timezone.model import ZonePrototypeError, ZoneRules, ZoneTransition",
        "",
        "def fixture_rules(zone_name: str) -> ZoneRules:",
    ]
    with tempfile.TemporaryDirectory(prefix="chronos-tz-fixture-") as directory:
        root = Path(directory)
        with tarfile.open(archive) as source:
            for name in SOURCE_FILES:
                member = source.extractfile(name)
                if member is None:
                    raise ValueError(f"missing IANA source: {name}")
                (root / name).write_bytes(member.read())
        compiled = root / "compiled"
        run("zic", "-d", str(compiled), *(str(root / name) for name in SOURCE_FILES))
        for name, first, end in CASES:
            with (compiled / name).open("rb") as stream:
                zone = ZoneInfo.from_file(stream, key=name)
            start_seconds, end_seconds = utc_start(first), utc_start(end)
            initial_offset = offset_at(zone, start_seconds)
            dump = run("zdump", "-V", "-c", f"{first},{end}", name, env={**ENV, "TZDIR": str(compiled)})
            pairs = []
            for line in dump.splitlines():
                instant, detail = line.removeprefix(name).strip().split(" UT = ", 1)
                utc = int(dt.datetime.strptime(instant, "%a %b %d %H:%M:%S %Y").replace(tzinfo=dt.timezone.utc).timestamp())
                offset = int(detail.rsplit("gmtoff=", 1)[1])
                if offset_at(zone, utc) != offset:
                    raise ValueError("zoneinfo and zdump offsets differ")
                pairs.append((utc, offset))
            if len(pairs) % 2:
                raise ValueError("unpaired zdump boundary")
            transitions = []
            for (before, old), (after, new) in zip(pairs[::2], pairs[1::2]):
                if after != before + 1 or old == new or not start_seconds < after < end_seconds:
                    raise ValueError("unexpected zdump boundary")
                transitions.append(f"ZoneTransition({after * 1000}, {new})")
            lines.append(f'    if zone_name == "{name}":')
            lines.append(f"        return ZoneRules({start_seconds * 1000}, {end_seconds * 1000}, {initial_offset}, [{', '.join(transitions)}])")
    lines.append('    raise ZonePrototypeError("unknown timezone fixture")')
    lines.extend([
        "",
        "class FixtureZoneProvider:",
        "    def version(self) -> str:",
        "",
        f'        return "{TZDATA_VERSION}"',
        "",
        "    def rules_for(self, zone_name: str) -> ZoneRules:",
        "",
        "        return fixture_rules(zone_name)",
    ])
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: generate_timezone_fixture.py tzdata2026f.tar.gz")
    print(fixture(Path(sys.argv[1])), end="")
